CREATE TABLE vaccination_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    pet_id BIGINT NOT NULL,
    vaccine_name VARCHAR(120) NOT NULL,
    vaccination_date DATE NOT NULL,
    next_date DATE NULL,
    hospital VARCHAR(160) NULL,
    batch_number VARCHAR(100) NULL,
    remark VARCHAR(500) NULL,
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    update_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_vaccination_pet_date (pet_id, deleted, vaccination_date, id),
    KEY idx_vaccination_reminder (pet_id, deleted, next_date),
    CONSTRAINT fk_vaccination_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT chk_vaccination_name CHECK (LENGTH(TRIM(vaccine_name)) > 0),
    CONSTRAINT chk_vaccination_next_date CHECK (next_date IS NULL OR next_date >= vaccination_date),
    CONSTRAINT chk_vaccination_deleted CHECK (deleted IN (0, 1))
);

CREATE TABLE deworming_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    pet_id BIGINT NOT NULL,
    type VARCHAR(16) NOT NULL,
    medicine_name VARCHAR(160) NULL,
    deworming_date DATE NOT NULL,
    next_date DATE NULL,
    remark VARCHAR(500) NULL,
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    update_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_deworming_pet_date (pet_id, deleted, deworming_date, id),
    KEY idx_deworming_reminder (pet_id, deleted, next_date),
    CONSTRAINT fk_deworming_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT chk_deworming_type CHECK (type IN ('INTERNAL', 'EXTERNAL', 'BOTH')),
    CONSTRAINT chk_deworming_next_date CHECK (next_date IS NULL OR next_date >= deworming_date),
    CONSTRAINT chk_deworming_deleted CHECK (deleted IN (0, 1))
);

CREATE TABLE medical_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    pet_id BIGINT NOT NULL,
    visit_date DATE NOT NULL,
    hospital VARCHAR(160) NULL,
    reason VARCHAR(500) NOT NULL,
    examination VARCHAR(2000) NULL,
    result VARCHAR(2000) NULL,
    medicine VARCHAR(1000) NULL,
    doctor_advice VARCHAR(2000) NULL,
    cost DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    next_visit_date DATE NULL,
    remark VARCHAR(500) NULL,
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    update_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_medical_pet_date (pet_id, deleted, visit_date, id),
    KEY idx_medical_reminder (pet_id, deleted, next_visit_date),
    CONSTRAINT fk_medical_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT chk_medical_reason CHECK (LENGTH(TRIM(reason)) > 0),
    CONSTRAINT chk_medical_cost CHECK (cost >= 0.00),
    CONSTRAINT chk_medical_next_visit_date CHECK (next_visit_date IS NULL OR next_visit_date >= visit_date),
    CONSTRAINT chk_medical_deleted CHECK (deleted IN (0, 1))
);
